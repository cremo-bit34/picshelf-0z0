for (const lang of Object.keys(KEYS_3D)) {
  const dict = KEYS_3D[lang];
  const langRegex = new RegExp(`(^|\\s)${lang}:\\s*\\{`, 'm');
  const match = content.match(langRegex);
  if (!match) {
    console.error('Could not find lang:', lang);
    continue;
  }
  const insertIndex = match.index + match[0].length;
  let codeToInsert = '\n';
  for (const [k, v] of Object.entries(dict)) {
    const escapedVal = v.replace(/'/g, "\\'");
    codeToInsert += `      ${k}: '${escapedVal}',\n`;
  }
  content = content.slice(0, insertIndex) + codeToInsert + content.slice(insertIndex);
}

